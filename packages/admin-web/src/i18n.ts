export function initialLocale(): Locale {
  const saved = globalThis.localStorage?.getItem(localeKey);
  if (saved === 'zh-CN' || saved === 'en') return saved;
  return globalThis.navigator?.language?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function saveLocale(locale: Locale): void {
  globalThis.localStorage?.setItem(localeKey, locale);
  document.documentElement.lang = locale;
}

export function translate(locale: Locale, message: string, values: Readonly<Record<string, string | number>> = {}): string {
  const [summary = message, ...details] = message.split('\n');
  const template = locale === 'zh-CN' ? (zhCN[summary] ?? summary) : summary;
  const translated = template.replace(/\{([a-z]+)\}/gi, (_match, key: string) => String(values[key] ?? `{${key}}`));
  return details.length > 0 ? `${translated}\n${details.join('\n')}` : translated;
}
