import { verifyLocalMcp } from '../src/mcp-local-install.js';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm, stat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { spawn } from 'node:child_process';
import { buildServer } from '../src/app.js';
import { loadConfig } from '../src/config.js';
import { migrate } from '../src/migrate.js';

test('quick MCP creates a reusable least-privilege local configuration without exposing its token', async (t) => {
  const dataDir = await mkdtemp(join(tmpdir(), 'voicecan-quick-mcp-'));
  const config = await loadConfig({ VOICECAN_DATA_DIR: dataDir, VOICECAN_PUBLIC_BASE_URL: 'http://127.0.0.1:8787', VOICECAN_LOG_LEVEL: 'silent' });
  migrate(config); const app = await buildServer(config);
  config.publicBaseUrl = await app.listen({ port: 0, host: '127.0.0.1' });
  t.after(async () => { await app.close(); await rm(dataDir, { recursive: true, force: true }); });
  const setup = await app.inject({ method: 'POST', url: '/api/v1/setup/admin', payload: { setup_token: (await readFile(join(dataDir, 'setup-token'), 'utf8')).trim(), username: 'admin', password: 'correct horse battery staple' } });
  const login = await app.inject({ method: 'POST', url: '/api/v1/auth/login', payload: { username: 'admin', password: 'correct horse battery staple' } });
  const headers = { cookie: String(login.headers['set-cookie']).split(';')[0]!, 'x-csrf-token': login.json().data.csrf_token, origin: config.publicBaseUrl };
  const url = '/api/v1/open-platform/mcp-quick-connect';
  const payload = { group_id: setup.json().data.group_id, client: 'codex' };
  assert.equal((await app.inject({ url, headers })).json().data.can_install, true);
  assert.equal((await app.inject({ method: 'POST', url, headers, payload: { ...payload, install: 'true' } })).statusCode, 400);
  assert.equal((await app.inject({ method: 'POST', url, headers, payload: { ...payload, client: 'claude', install: true } })).statusCode, 404);
  const created = await app.inject({ method: 'POST', url, headers, payload });
  assert.equal(created.statusCode, 200, created.body);
  const plan = created.json().data;
  assert.deepEqual(plan.scopes, ['devices:read', 'recordings:read', 'events:read']);
  assert.equal(created.body.includes('vcd_app_'), false);
  const secret = (await readFile(plan.secret_ref, 'utf8')).trim();
  assert.equal((await stat(plan.secret_ref)).mode & 0o077, 0);
  const capabilities = await app.inject({ url: '/api/v1/capabilities', headers: { authorization: `Bearer ${secret}` } });
  assert.equal(capabilities.statusCode, 200);
  assert.equal(capabilities.json().data.channel, 'mcp_stdio');
  assert.deepEqual(capabilities.json().data.scopes.sort(), [...plan.scopes].sort());
  const entry = plan.config.mcpServers.voicecan_elio;
  assert.equal(await verifyLocalMcp(entry), 6);
  const child = spawn(entry.command, entry.args, { stdio: ['pipe', 'pipe', 'pipe'] });
  const messages = await new Promise<Record<string, any>[]>((resolve, reject) => {
    const timeout = setTimeout(() => { child.kill(); reject(new Error('Generated MCP did not respond')); }, 10_000);
    let output = '';
    child.stdout.on('data', (data) => {
      output += String(data);
      const lines = output.trim().split('\n');
      if (lines.length >= 2 && output.endsWith('\n')) { clearTimeout(timeout); child.stdin.end(); resolve(lines.map((line) => JSON.parse(line))); }
    });
    child.once('error', (error) => { clearTimeout(timeout); reject(error); });
    child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2025-11-25' } }) + '\n');
    child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: 2, method: 'tools/list', params: {} }) + '\n');
  });
  assert.equal(messages[0]!.result.serverInfo.name, '@voicecan/device-mcp');
  assert.equal(messages[1]!.result.tools.length, 6);
  assert.ok(messages[1]!.result.tools.every((tool: { annotations: { readOnlyHint: boolean } }) => tool.annotations.readOnlyHint));
  const reused = await app.inject({ method: 'POST', url, headers, payload });
  assert.equal(reused.statusCode, 200, reused.body);
  assert.equal(reused.json().data.credential_id, plan.credential_id);
  const otherClient = await app.inject({ method: 'POST', url, headers, payload: { ...payload, client: 'claude' } });
  assert.equal(otherClient.json().data.credential_id, plan.credential_id, 'changing client format must not create more credentials');
  assert.equal((await app.inject({ method: 'POST', url, headers: { cookie: headers.cookie, origin: config.publicBaseUrl }, payload })).statusCode, 403);
  assert.equal((await app.inject({ method: 'POST', url, headers, payload: { ...payload, scopes: ['devices:sync'] } })).statusCode, 400);
  assert.equal((await app.inject({ method: 'POST', url, headers: { ...headers, origin: 'http://evil.invalid' }, payload })).statusCode, 403);
  assert.equal((await app.inject({ method: 'POST', url, headers, payload, remoteAddress: '192.168.0.10' })).statusCode, 403);
  const withoutConsent = await app.inject({ method: 'POST', url, headers, payload: { ...payload, access: 'recordings' } });
  assert.equal(withoutConsent.statusCode, 400);
  assert.equal(withoutConsent.json().code, 'RECORDING_CONSENT_REQUIRED');
  const audio = await app.inject({ method: 'POST', url, headers, payload: { ...payload, client: 'openclaw', access: 'recordings', consent: true } });
  assert.equal(audio.statusCode, 200, audio.body);
  const audioPlan = audio.json().data;
  assert.notEqual(audioPlan.credential_id, plan.credential_id, 'content access must not widen a metadata credential');
  assert.deepEqual(audioPlan.scopes, [...plan.scopes, 'recordings:download_link:create', 'recordings:download_link:revoke']);
  assert.equal(audio.body.includes('vcd_app_'), false);
  const openclaw = JSON.parse(audioPlan.configuration).mcp.servers.voicecan_elio_recordings;
  assert.equal(openclaw.transport, 'stdio');
  assert.equal(openclaw.enabled, true);
  assert.ok(audioPlan.install_command.startsWith("'openclaw' 'mcp' 'add'"));
  assert.ok(audioPlan.verify_command.includes("'--probe'"));
  assert.equal(audioPlan.installation, null, 'generated configuration is not a client installation');
  assert.equal(await verifyLocalMcp(openclaw), 8);
  const metadataAfter = await app.inject({ method: 'POST', url, headers, payload });
  assert.equal(metadataAfter.json().data.credential_id, plan.credential_id);
  const audioAgain = await app.inject({ method: 'POST', url, headers, payload: { ...payload, client: 'openclaw', access: 'recordings', consent: true } });
  assert.equal(audioAgain.json().data.credential_id, audioPlan.credential_id);
  assert.equal((await app.inject({ method:'POST', url, headers, payload:{...payload,access:'control',consent:true} })).statusCode,400);
  const revoked = await app.inject({ method: 'DELETE', url: `/api/v1/open-platform/applications/${plan.application_id}/credentials/${plan.credential_id}`, headers, payload: { reason: 'Test revocation' } });
  assert.equal(revoked.statusCode, 200, revoked.body);
  const noSilentRotation = await app.inject({ method: 'POST', url, headers, payload });
  assert.equal(noSilentRotation.statusCode, 409);
});
